-- V5: tables of the Assets context (AP-371 / P-371.1): devices, edges and device networks.
--
-- The Assets aggregates arrived after the V1 baseline, so a database built only by Flyway
-- had no tables for them and failed Hibernate's ddl-auto=validate (the production setting).
--
-- The MAC address is stored in its canonical form (upper case, colon separated; see the
-- MacAddress value object) and is unique per table. A device and an edge cannot share a MAC
-- either, but that rule spans two tables and is enforced by the command services.
--
-- Status and type columns hold the enum names (EnumType.STRING), not their ordinal.
--
-- IF NOT EXISTS keeps databases where ddl-auto=update already created some of these tables
-- from failing. Those databases hold the earlier ordinal mapping (smallint status/type
-- columns) and no alias column; they are not repaired here. Drop the unreleased tables
-- devices, edges, device_networks and network_actuators before running this migration.

CREATE TABLE IF NOT EXISTS devices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    business_id bigint NOT NULL,
    mac_address character varying(17) NOT NULL,
    asset_status character varying(16) NOT NULL,
    alias character varying(80) NOT NULL,
    device_type character varying(16) NOT NULL,
    CONSTRAINT uk_devices_mac_address UNIQUE (mac_address),
    CONSTRAINT devices_asset_status_check
        CHECK (asset_status IN ('AVAILABLE', 'IN_USE', 'MAINTENANCE', 'BROKEN', 'RETIRED')),
    CONSTRAINT devices_device_type_check
        CHECK (device_type IN ('MICROPHONE', 'DOOR', 'WINDOW', 'CURTAIN', 'LIGHT'))
);

CREATE TABLE IF NOT EXISTS edges (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    business_id bigint NOT NULL,
    mac_address character varying(17) NOT NULL,
    asset_status character varying(16) NOT NULL,
    edge_type character varying(255) NOT NULL,
    CONSTRAINT uk_edges_mac_address UNIQUE (mac_address),
    CONSTRAINT edges_asset_status_check
        CHECK (asset_status IN ('AVAILABLE', 'IN_USE', 'MAINTENANCE', 'BROKEN', 'RETIRED')),
    CONSTRAINT edges_edge_type_check
        CHECK (edge_type IN ('MICROPHONE_EDGE', 'ACTUATOR_EDGE'))
);

CREATE TABLE IF NOT EXISTS device_networks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    business_id bigint,
    installation_id bigint,
    network_status character varying(255),
    microphone_edge bigint,
    actuator_id bigint,
    microphone_id bigint,
    CONSTRAINT uk_device_networks_microphone_edge UNIQUE (microphone_edge),
    CONSTRAINT uk_device_networks_actuator_edge UNIQUE (actuator_id),
    CONSTRAINT uk_device_networks_microphone UNIQUE (microphone_id),
    CONSTRAINT device_networks_network_status_check
        CHECK (network_status IN ('ACTIVE', 'DEACTIVATED', 'DISMANTLED')),
    CONSTRAINT fk_device_networks_microphone_edge
        FOREIGN KEY (microphone_edge) REFERENCES edges (id),
    CONSTRAINT fk_device_networks_actuator_edge
        FOREIGN KEY (actuator_id) REFERENCES edges (id),
    CONSTRAINT fk_device_networks_microphone
        FOREIGN KEY (microphone_id) REFERENCES devices (id)
);

CREATE TABLE IF NOT EXISTS network_actuators (
    network_id bigint NOT NULL,
    device_id bigint NOT NULL,
    CONSTRAINT uk_network_actuators_device_id UNIQUE (device_id),
    CONSTRAINT fk_network_actuators_network
        FOREIGN KEY (network_id) REFERENCES device_networks (id),
    CONSTRAINT fk_network_actuators_device
        FOREIGN KEY (device_id) REFERENCES devices (id)
);
