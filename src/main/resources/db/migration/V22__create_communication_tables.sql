-- V22: Communication tables (Alert, Notification, Email, PushDevice)

CREATE TABLE IF NOT EXISTS alerts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id bigint NOT NULL,
    help_request_id character varying(64) NOT NULL,
    title character varying(150) NOT NULL,
    body text NOT NULL,
    status character varying(12) NOT NULL,
    sent_at timestamp(6) without time zone,
    attempts integer NOT NULL DEFAULT 0,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT alerts_status_check
        CHECK (status IN ('PENDING', 'SENT', 'UNDELIVERED'))
);

CREATE INDEX IF NOT EXISTS idx_alerts_recipient_created
    ON alerts (recipient_user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_alerts_status_attempts
    ON alerts (status, attempts);

CREATE TABLE IF NOT EXISTS notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id bigint NOT NULL,
    type character varying(25) NOT NULL,
    source_id character varying(64) NOT NULL,
    title character varying(150) NOT NULL,
    body text NOT NULL,
    status character varying(10) NOT NULL,
    read_at timestamp(6) without time zone,
    push_status character varying(12) NOT NULL,
    push_attempts integer NOT NULL DEFAULT 0,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT notifications_status_check
        CHECK (status IN ('UNREAD', 'READ')),
    CONSTRAINT notifications_push_status_check
        CHECK (push_status IN ('PENDING', 'SENT', 'UNDELIVERED'))
);

CREATE INDEX IF NOT EXISTS idx_notifications_recipient_status_created
    ON notifications (recipient_user_id, status, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_notifications_push_status_attempts
    ON notifications (push_status, push_attempts);

CREATE TABLE IF NOT EXISTS emails (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_address character varying(254) NOT NULL,
    template character varying(30) NOT NULL,
    status character varying(10) NOT NULL,
    sent_at timestamp(6) without time zone,
    failure_reason character varying(500),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT emails_status_check
        CHECK (status IN ('PENDING', 'SENT', 'FAILED'))
);

CREATE INDEX IF NOT EXISTS idx_emails_status_created
    ON emails (status, created_at DESC);

CREATE TABLE IF NOT EXISTS push_devices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    token character varying(512) NOT NULL,
    platform character varying(10) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_push_devices_token UNIQUE (token),
    CONSTRAINT push_devices_platform_check
        CHECK (platform IN ('ANDROID', 'IOS'))
);

CREATE INDEX IF NOT EXISTS idx_push_devices_user_id
    ON push_devices (user_id);
