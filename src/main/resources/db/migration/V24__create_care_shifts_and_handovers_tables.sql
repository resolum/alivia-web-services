-- V24: Care Shifts and Handovers (Assistance Bounded Context)

CREATE TABLE IF NOT EXISTS care_shifts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assisted_person_id bigint NOT NULL,
    caregiver_id bigint NOT NULL,
    caregiver_name character varying(150) NOT NULL,
    starts_at timestamp(6) without time zone NOT NULL,
    ends_at timestamp(6) without time zone NOT NULL,
    notes text,
    status character varying(20) NOT NULL DEFAULT 'SCHEDULED',
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT care_shifts_status_check
        CHECK (status IN ('SCHEDULED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED'))
);

CREATE INDEX IF NOT EXISTS idx_care_shifts_assisted_person_dates
    ON care_shifts (assisted_person_id, starts_at, ends_at);

CREATE INDEX IF NOT EXISTS idx_care_shifts_caregiver
    ON care_shifts (caregiver_id);

CREATE TABLE IF NOT EXISTS care_handovers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_shift_id bigint NOT NULL,
    to_shift_id bigint NOT NULL,
    from_caregiver_id bigint NOT NULL,
    from_caregiver_name character varying(150) NOT NULL,
    to_caregiver_id bigint NOT NULL,
    to_caregiver_name character varying(150) NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'PENDING',
    requested_at timestamp(6) without time zone NOT NULL,
    responded_at timestamp(6) without time zone,
    escalated_at timestamp(6) without time zone,
    attended_tasks text,
    pending_tasks text,
    substitute boolean NOT NULL DEFAULT FALSE,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT care_handovers_status_check
        CHECK (status IN ('PENDING', 'DECLINED', 'ACCEPTED', 'REASSIGNED')),
    CONSTRAINT fk_care_handovers_from_shift
        FOREIGN KEY (from_shift_id) REFERENCES care_shifts (id) ON DELETE CASCADE,
    CONSTRAINT fk_care_handovers_to_shift
        FOREIGN KEY (to_shift_id) REFERENCES care_shifts (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_care_handovers_from_shift
    ON care_handovers (from_shift_id);

CREATE INDEX IF NOT EXISTS idx_care_handovers_to_shift
    ON care_handovers (to_shift_id);

CREATE INDEX IF NOT EXISTS idx_care_handovers_status
    ON care_handovers (status);
