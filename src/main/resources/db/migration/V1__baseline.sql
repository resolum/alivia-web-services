-- V1: full schema of the Alivia web services (AP-480 / P-480.2).
--
-- Captured from the JPA entities: the application was started once against an empty
-- PostgreSQL 18 database with spring.jpa.hibernate.ddl-auto=update, and the resulting
-- schema was dumped with pg_dump --schema-only. The dump was then reduced to plain DDL
-- (pg_dump session settings, ownership, \restrict markers and the "public." prefix were
-- removed), so this file applies to whatever schema Flyway uses by default.
--
-- It contains every table, column, check constraint, primary key, unique constraint,
-- index and foreign key Hibernate creates for the entities as of this commit.
--
-- Rules for this file and for every later migration:
--   * Once applied anywhere, a migration is immutable: Flyway stores a checksum and a
--     mismatch aborts the startup. Change the schema with a new V<n>__*.sql file.
--   * Keep the names of tables, columns and types identical to what Hibernate expects.
--     Production will run with ddl-auto=validate (P-464.2), so any divergence fails at startup.
--   * Add new objects with the next free version; never edit an applied migration.
--
-- Databases created by Hibernate before Flyway was adopted are baselined at version 1
-- (spring.flyway.baseline-on-migrate=true) and skip this file. That is only correct
-- while this file matches the schema those databases already have.

