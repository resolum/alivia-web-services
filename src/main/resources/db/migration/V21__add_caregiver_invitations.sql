-- V21: caregiver invitations (nursing, CaregiverInvitation).
--
-- Caregiver invitations allow household managers to invite relatives and health professionals
-- to the care network with designated responsibilities. The invited caregiver receives an email
-- with a unique token to view and accept or reject the invitation.

CREATE TABLE IF NOT EXISTS caregiver_invitations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    token character varying(64) NOT NULL,
    household_id bigint NOT NULL,
    assisted_person_profile_id bigint NOT NULL,
    email character varying(180) NOT NULL,
    inviter_user_id bigint NOT NULL,
    relationship character varying(60) NOT NULL,
    status character varying(20) NOT NULL,
    expires_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_caregiver_invitations_token UNIQUE (token),
    CONSTRAINT caregiver_invitations_status_check
        CHECK (status IN ('ACTIVE', 'ACCEPTED', 'REJECTED', 'EXPIRED', 'CANCELLED'))
);

CREATE TABLE IF NOT EXISTS caregiver_invitation_responsibilities (
    invitation_id bigint NOT NULL,
    responsibility character varying(60) NOT NULL,
    CONSTRAINT fk_caregiver_invitation_responsibilities_invitation
        FOREIGN KEY (invitation_id) REFERENCES caregiver_invitations (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_caregiver_invitations_household
    ON caregiver_invitations (household_id);

CREATE INDEX IF NOT EXISTS idx_caregiver_invitations_household_email
    ON caregiver_invitations (household_id, email);
