-- V25: Create assistance bounded context core tables and enrich assisted_persons
--
-- Tables for the Assistance bounded context:
-- relatives, assisted_persons, caregivers, assistance_invitations.

CREATE TABLE IF NOT EXISTS relatives (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    user_id bigint NOT NULL,
    person_profile_id bigint NOT NULL,
    business_id bigint NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_relatives_user_id ON relatives (user_id);
CREATE INDEX IF NOT EXISTS idx_relatives_person_profile_id ON relatives (person_profile_id);

CREATE TABLE IF NOT EXISTS assisted_persons (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    person_profile_id bigint NOT NULL,
    relative_id bigint NOT NULL,
    household_id bigint,
    kinship character varying(20),
    mobility_level character varying(20),
    emergency_contact_name character varying(150),
    emergency_contact_phone character varying(15),
    consent_given_at timestamp(6) without time zone,
    CONSTRAINT fk_assisted_persons_relative
        FOREIGN KEY (relative_id) REFERENCES relatives (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_assisted_persons_relative ON assisted_persons (relative_id);
CREATE INDEX IF NOT EXISTS idx_assisted_persons_profile ON assisted_persons (person_profile_id);
CREATE INDEX IF NOT EXISTS idx_assisted_persons_household ON assisted_persons (household_id);

-- Backwards compatibility in case assisted_persons was previously created with fewer columns
ALTER TABLE assisted_persons
    ADD COLUMN IF NOT EXISTS household_id BIGINT,
    ADD COLUMN IF NOT EXISTS kinship VARCHAR(20),
    ADD COLUMN IF NOT EXISTS mobility_level VARCHAR(20),
    ADD COLUMN IF NOT EXISTS emergency_contact_name VARCHAR(150),
    ADD COLUMN IF NOT EXISTS emergency_contact_phone VARCHAR(15),
    ADD COLUMN IF NOT EXISTS consent_given_at TIMESTAMP WITHOUT TIME ZONE;

CREATE TABLE IF NOT EXISTS caregivers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    user_id bigint NOT NULL,
    assisted_person_id bigint NOT NULL,
    status character varying(20) NOT NULL,
    CONSTRAINT fk_caregivers_assisted_person
        FOREIGN KEY (assisted_person_id) REFERENCES assisted_persons (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_caregivers_user ON caregivers (user_id);
CREATE INDEX IF NOT EXISTS idx_caregivers_assisted_person ON caregivers (assisted_person_id);

CREATE TABLE IF NOT EXISTS assistance_invitations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    assisted_person_id bigint NOT NULL,
    inviter_id bigint NOT NULL,
    invitee_email character varying(255) NOT NULL,
    caregiver_user_id bigint,
    status character varying(20) NOT NULL,
    expires_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT fk_assistance_invitations_assisted_person
        FOREIGN KEY (assisted_person_id) REFERENCES assisted_persons (id) ON DELETE CASCADE,
    CONSTRAINT fk_assistance_invitations_inviter
        FOREIGN KEY (inviter_id) REFERENCES relatives (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_assistance_invitations_assisted_person ON assistance_invitations (assisted_person_id);
CREATE INDEX IF NOT EXISTS idx_assistance_invitations_inviter ON assistance_invitations (inviter_id);
CREATE INDEX IF NOT EXISTS idx_assistance_invitations_email ON assistance_invitations (invitee_email);
