-- V18: care profile of the assisted person (nursing, AssistedPersonCareProfile).
--
-- The entity reached develop and main without a migration: it only worked where ddl-auto=update creates tables (dev),
-- and the application cannot start with ddl-auto=validate (prod) without this table. The columns are exactly the ones
-- the entity maps; a responsible client has one profile (uk_..._registered_by).
--
-- IF NOT EXISTS keeps databases where the table was already created (ddl-auto=update, or by hand) from failing.

CREATE TABLE IF NOT EXISTS assisted_person_care_profiles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    registered_by_user_id bigint NOT NULL,
    household_id bigint,
    first_name character varying(75) NOT NULL,
    last_name character varying(75) NOT NULL,
    birth_date date NOT NULL,
    document_type character varying(10),
    document_number character varying(12),
    kinship character varying(20) NOT NULL,
    phone_number character varying(15),
    mobility_level character varying(20) NOT NULL,
    emergency_contact_name character varying(150),
    emergency_contact_phone character varying(15),
    consent_given_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_assisted_person_care_profiles_registered_by UNIQUE (registered_by_user_id),
    CONSTRAINT assisted_person_care_profiles_document_type_check
        CHECK (document_type IN ('CE', 'DNI', 'PASSPORT')),
    CONSTRAINT assisted_person_care_profiles_kinship_check
        CHECK (kinship IN ('AUNT_UNCLE', 'GRANDPARENT', 'OTHER', 'PARENT', 'SIBLING', 'SPOUSE')),
    CONSTRAINT assisted_person_care_profiles_mobility_level_check
        CHECK (mobility_level IN ('NO_LIMB_MOBILITY', 'PARTIAL', 'VERY_LIMITED'))
);
