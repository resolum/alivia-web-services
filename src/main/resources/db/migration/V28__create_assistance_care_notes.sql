-- V28: care notes of an assisted person (TS-17). A note is never edited: a correction is a new note.

CREATE TABLE assistance_care_notes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    assisted_person_id bigint NOT NULL,
    author_user_id bigint NOT NULL,
    category character varying(20) NOT NULL,
    content character varying(1000) NOT NULL,
    CONSTRAINT assistance_care_notes_category_check
        CHECK (category IN ('GENERAL', 'HEALTH', 'MEDICATION', 'FEEDING', 'MOOD', 'INCIDENT')),
    CONSTRAINT fk_assistance_care_notes_assisted_person
        FOREIGN KEY (assisted_person_id) REFERENCES assisted_persons (id)
);

-- The summary reads the notes of a person in a period.
CREATE INDEX ix_care_note_person_created ON assistance_care_notes (assisted_person_id, created_at);
