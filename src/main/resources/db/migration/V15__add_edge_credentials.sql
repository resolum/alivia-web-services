-- V15: credentials of the edge services (AP-68, transport towards the edge services).
--
-- Each edge service of a household (microphone and actuators) identifies itself to the API with its own secret. Only
-- the SHA-256 hash of the secret is stored. edge_id is the inventory id of the edge (assets context); there is no
-- foreign key because the two contexts keep their tables apart.
--
-- IF NOT EXISTS keeps databases where ddl-auto=update already created the table from failing.

CREATE TABLE IF NOT EXISTS edge_credentials (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    edge_id bigint NOT NULL,
    edge_kind character varying(16) NOT NULL,
    secret_hash character varying(64) NOT NULL,
    last_used_at timestamp(6) without time zone,
    revoked_at timestamp(6) without time zone,
    CONSTRAINT uk_edge_credentials_edge UNIQUE (edge_id),
    CONSTRAINT edge_credentials_edge_kind_check CHECK (edge_kind IN ('MICROPHONE', 'ACTUATOR'))
);
