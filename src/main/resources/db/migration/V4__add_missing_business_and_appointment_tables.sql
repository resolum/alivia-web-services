-- V4: adds the tables that V1 missed because their aggregates arrived after the baseline.
--
-- V1 was captured from the entities as of AP-480. Administrator and Business were added
-- later (e8391b6) and Appointment was moved to Operations (325412d), so a fresh database
-- built only by Flyway failed Hibernate's ddl-auto=validate before any later migration
-- could run.
--
-- IF NOT EXISTS keeps local databases where ddl-auto=update already created the tables
-- from failing: Hibernate generated the same columns, checks, unique constraints and the
-- association foreign key from the entity annotations. The index is created separately and
-- is idempotent for the same reason.

CREATE TABLE IF NOT EXISTS administrators (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    user_id bigint NOT NULL,
    staff_profile_id bigint NOT NULL,
    backup_personal_email character varying(255)
);

CREATE TABLE IF NOT EXISTS businesses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    business_profile_id bigint,
    administrator_id bigint,
    CONSTRAINT uk_businesses_administrator UNIQUE (administrator_id),
    CONSTRAINT fk_businesses_administrator
        FOREIGN KEY (administrator_id) REFERENCES administrators (id)
);

CREATE TABLE IF NOT EXISTS appointments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    draft_id character varying(36) NOT NULL,
    scheduled_date date NOT NULL,
    start_time time(0) without time zone NOT NULL,
    end_time time(0) without time zone NOT NULL,
    technician_id bigint NOT NULL,
    technician_name character varying(120) NOT NULL,
    contact_name character varying(100) NOT NULL,
    contact_phone character varying(20) NOT NULL,
    directions character varying(300),
    status character varying(16) NOT NULL,
    CONSTRAINT uk_appointments_technician_window
        UNIQUE (technician_id, scheduled_date, start_time),
    CONSTRAINT uk_appointments_draft UNIQUE (draft_id),
    CONSTRAINT appointments_status_check
        CHECK (status IN ('SCHEDULED', 'CANCELED'))
);

CREATE INDEX IF NOT EXISTS idx_appointments_date_status
    ON appointments USING btree (scheduled_date, status);
