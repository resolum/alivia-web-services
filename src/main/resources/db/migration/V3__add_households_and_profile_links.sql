-- V3: links profiles to their IAM user, adds communication preferences and creates
-- households with their members (AP-356 / P-356.1).
--
-- The profile columns are nullable because existing rows and assisted persons without an
-- account have no user yet. Preferences stay nullable until the user sets them.
--
-- Hibernate validates tables, columns and types (ddl-auto=validate), not indexes, so the
-- partial unique indexes and the foreign key to users survive the production schema check.

ALTER TABLE person_profiles ADD COLUMN user_id bigint;
ALTER TABLE person_profiles ADD COLUMN preferences jsonb;

ALTER TABLE staff_profiles ADD COLUMN user_id bigint;
ALTER TABLE staff_profiles ADD COLUMN preferences jsonb;

ALTER TABLE business_profiles ADD COLUMN user_id bigint;
ALTER TABLE business_profiles ADD COLUMN preferences jsonb;

CREATE UNIQUE INDEX uk_person_profiles_user_id ON person_profiles USING btree (user_id)
    WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX uk_staff_profiles_user_id ON staff_profiles USING btree (user_id)
    WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX uk_business_profiles_user_id ON business_profiles USING btree (user_id)
    WHERE user_id IS NOT NULL;

CREATE TABLE households (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    alias character varying(120) NOT NULL,
    formatted_address character varying(255),
    latitude double precision,
    longitude double precision,
    place_id character varying(255),
    contact_phone character varying(255),
    contact_email character varying(255)
);

CREATE TABLE household_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    household_id bigint NOT NULL,
    user_id bigint NOT NULL,
    responsibility character varying(20) NOT NULL,
    status character varying(20) NOT NULL,
    CONSTRAINT fk_household_members_household
        FOREIGN KEY (household_id) REFERENCES households (id),
    CONSTRAINT fk_household_members_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_household_members_household_user
        UNIQUE (household_id, user_id),
    CONSTRAINT household_members_responsibility_check
        CHECK (responsibility IN ('PRINCIPAL', 'CAREGIVER', 'GUEST')),
    CONSTRAINT household_members_status_check
        CHECK (status IN ('ACTIVE', 'REVOKED'))
);

CREATE INDEX idx_household_members_user ON household_members USING btree (user_id);
