-- V26: isolate the Assistance activity model from the legacy Nursing tables.
--
-- Assistance originally reused care_activities, activity_assignments and activity_logs.
-- Those tables belong to the previous Nursing model and use profile/membership identifiers
-- and different column names. Keeping both models in the same tables made Hibernate validation
-- fail and would also make new writes violate legacy NOT NULL constraints. The legacy tables and
-- their data are deliberately preserved; Assistance owns the three tables below.

CREATE TABLE assistance_care_activities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    assisted_person_id bigint NOT NULL,
    type character varying(20) NOT NULL,
    title character varying(120) NOT NULL,
    description character varying(500),
    status character varying(20) NOT NULL,
    CONSTRAINT assistance_care_activities_type_check
        CHECK (type IN ('HYGIENE', 'MEDICATION', 'APPOINTMENT', 'THERAPY', 'MEAL', 'BATH', 'EXERCISE', 'OTHER')),
    CONSTRAINT assistance_care_activities_status_check
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT fk_assistance_care_activities_assisted_person
        FOREIGN KEY (assisted_person_id) REFERENCES assisted_persons (id)
);

CREATE INDEX idx_assistance_care_activities_assisted_person
    ON assistance_care_activities (assisted_person_id);

CREATE TABLE assistance_activity_assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    care_activity_id bigint NOT NULL,
    caregiver_id bigint,
    schedule_type character varying(20) NOT NULL,
    scheduled_date date,
    week_days character varying(80),
    start_time time(0) without time zone NOT NULL,
    end_time time(0) without time zone NOT NULL,
    status character varying(20) NOT NULL,
    CONSTRAINT assistance_activity_assignments_schedule_type_check
        CHECK (schedule_type IN ('ONE_TIME', 'WEEKLY')),
    CONSTRAINT assistance_activity_assignments_status_check
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT fk_assistance_activity_assignments_activity
        FOREIGN KEY (care_activity_id) REFERENCES assistance_care_activities (id) ON DELETE CASCADE,
    CONSTRAINT fk_assistance_activity_assignments_caregiver
        FOREIGN KEY (caregiver_id) REFERENCES caregivers (id)
);

CREATE INDEX idx_assistance_activity_assignments_activity
    ON assistance_activity_assignments (care_activity_id);
CREATE INDEX idx_assistance_activity_assignments_caregiver
    ON assistance_activity_assignments (caregiver_id);

CREATE TABLE assistance_activity_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    assisted_person_id bigint NOT NULL,
    care_activity_id bigint NOT NULL,
    assignment_id bigint NOT NULL,
    date date NOT NULL,
    title character varying(120) NOT NULL,
    start_time time(0) without time zone NOT NULL,
    end_time time(0) without time zone NOT NULL,
    assigned_caregiver_id bigint,
    status character varying(20) NOT NULL,
    completed_by_id bigint,
    completed_at timestamp(6) without time zone,
    notes character varying(500),
    CONSTRAINT uk_assistance_activity_log_assignment_date UNIQUE (assignment_id, date),
    CONSTRAINT assistance_activity_logs_status_check
        CHECK (status IN ('COMPLETED', 'CANCELLED', 'MISSED', 'OMITTED')),
    CONSTRAINT fk_assistance_activity_logs_assisted_person
        FOREIGN KEY (assisted_person_id) REFERENCES assisted_persons (id),
    CONSTRAINT fk_assistance_activity_logs_activity
        FOREIGN KEY (care_activity_id) REFERENCES assistance_care_activities (id),
    CONSTRAINT fk_assistance_activity_logs_assignment
        FOREIGN KEY (assignment_id) REFERENCES assistance_activity_assignments (id),
    CONSTRAINT fk_assistance_activity_logs_assigned_caregiver
        FOREIGN KEY (assigned_caregiver_id) REFERENCES caregivers (id),
    CONSTRAINT fk_assistance_activity_logs_completed_by
        FOREIGN KEY (completed_by_id) REFERENCES caregivers (id)
);

CREATE INDEX idx_assistance_activity_logs_assisted_person_date
    ON assistance_activity_logs (assisted_person_id, date);
CREATE INDEX idx_assistance_activity_logs_caregiver_date
    ON assistance_activity_logs (assigned_caregiver_id, date);
