CREATE TABLE edge_provisioning_tokens (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL,
 edge_id bigint NOT NULL, token_hash varchar(64) NOT NULL,
 expires_at timestamp(6) NOT NULL, used_at timestamp(6), issued_by bigint NOT NULL,
 CONSTRAINT uk_edge_provisioning_edge UNIQUE(edge_id),
 CONSTRAINT uk_edge_provisioning_hash UNIQUE(token_hash),
 CONSTRAINT fk_edge_provisioning_edge FOREIGN KEY(edge_id) REFERENCES edges(id)
);
