-- V6: assignment of a device to a household (AP-376 / P-376.1).
--
-- A device belongs to the business inventory (devices.business_id). It reaches a household when it is
-- assigned to a room with a function; that placement is stored here. An assignment is active while
-- unassigned_at is null. Closing it instead of deleting it keeps the history (AP-373).
--
-- household_id is a plain number: the household lives in Profiles and no foreign key crosses contexts.
-- room_key is the key of the room of the contracted configuration, which has no table of its own.
--
-- A device can have only one active assignment. That is a partial unique index, which Hibernate cannot
-- declare from the entity, so it only exists through this migration.
--
-- IF NOT EXISTS keeps databases where ddl-auto=update already created the table from failing.

CREATE TABLE IF NOT EXISTS device_assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    device_id bigint NOT NULL,
    household_id bigint NOT NULL,
    room_key character varying(60) NOT NULL,
    device_function character varying(80) NOT NULL,
    assigned_by bigint NOT NULL,
    assigned_at timestamp(6) without time zone NOT NULL,
    unassigned_at timestamp(6) without time zone,
    CONSTRAINT fk_device_assignments_device
        FOREIGN KEY (device_id) REFERENCES devices (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_device_assignments_active_device
    ON device_assignments (device_id)
    WHERE unassigned_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_device_assignments_household_active
    ON device_assignments (household_id, room_key)
    WHERE unassigned_at IS NULL;
