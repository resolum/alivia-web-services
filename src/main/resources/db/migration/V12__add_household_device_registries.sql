-- V12: one registry of devices per household (AP-68, HouseholdDeviceRegistry).
--
-- Until now the detail of a household's devices was split between device_networks (installation, status, edge services),
-- the active rows of device_assignments and a table computed on demand. The registry brings them together: one row per
-- household with the installation, the status, the edge services and the version of the table of devices, and its active
-- device_assignments rows as its entries. Closed rows stay in device_assignments as history.
--
-- Data is moved before device_networks is dropped:
--   * each network becomes the registry of its household (a household with several keeps its active one);
--   * a household with active assignments but no network gets a registry from the installation of those assignments;
--   * every assignment is linked to the registry of its household.
-- table_version starts at 0: no edge service has received a table yet.
--
-- IF NOT EXISTS keeps databases where ddl-auto=update already created the table from failing.

CREATE TABLE IF NOT EXISTS household_device_registries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    business_id bigint NOT NULL,
    household_id bigint NOT NULL,
    installation_id bigint NOT NULL,
    status character varying(16) NOT NULL,
    table_version bigint NOT NULL,
    microphone_edge bigint,
    actuator_edge bigint,
    CONSTRAINT uk_household_device_registries_household UNIQUE (household_id),
    CONSTRAINT uk_household_device_registries_installation UNIQUE (installation_id),
    CONSTRAINT uk_household_device_registries_microphone_edge UNIQUE (microphone_edge),
    CONSTRAINT uk_household_device_registries_actuator_edge UNIQUE (actuator_edge),
    CONSTRAINT household_device_registries_status_check
        CHECK (status IN ('ACTIVE', 'DEACTIVATED', 'DISMANTLED')),
    CONSTRAINT fk_household_device_registries_microphone_edge
        FOREIGN KEY (microphone_edge) REFERENCES edges (id),
    CONSTRAINT fk_household_device_registries_actuator_edge
        FOREIGN KEY (actuator_edge) REFERENCES edges (id)
);

ALTER TABLE device_assignments
    ADD COLUMN IF NOT EXISTS registry_id bigint;

-- 1. the networks
INSERT INTO household_device_registries
    (created_at, updated_at, business_id, household_id, installation_id, status, table_version, microphone_edge, actuator_edge)
SELECT DISTINCT ON (household_id)
    created_at, updated_at, business_id, household_id, installation_id, network_status, 0, microphone_edge, actuator_id
FROM device_networks
WHERE household_id IS NOT NULL AND business_id IS NOT NULL AND installation_id IS NOT NULL
ORDER BY household_id, (network_status = 'ACTIVE') DESC, id DESC
ON CONFLICT DO NOTHING;

-- 2. households whose devices have no network
INSERT INTO household_device_registries
    (created_at, updated_at, business_id, household_id, installation_id, status, table_version)
SELECT DISTINCT ON (a.household_id)
    now(), now(), d.business_id, a.household_id, a.installation_id, 'ACTIVE', 0
FROM device_assignments a
JOIN devices d ON d.id = a.device_id
WHERE a.installation_id IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM household_device_registries r WHERE r.household_id = a.household_id)
  AND NOT EXISTS (SELECT 1 FROM household_device_registries r WHERE r.installation_id = a.installation_id)
ORDER BY a.household_id, a.id DESC
ON CONFLICT DO NOTHING;

-- 3. the assignments
UPDATE device_assignments a
    SET registry_id = r.id
    FROM household_device_registries r
    WHERE r.household_id = a.household_id
      AND a.registry_id IS NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_device_assignments_registry') THEN
        ALTER TABLE device_assignments
            ADD CONSTRAINT fk_device_assignments_registry
                FOREIGN KEY (registry_id) REFERENCES household_device_registries (id);
    END IF;
END
$$;

CREATE INDEX IF NOT EXISTS idx_device_assignments_registry_active
    ON device_assignments (registry_id)
    WHERE unassigned_at IS NULL;

DROP TABLE IF EXISTS device_networks;
